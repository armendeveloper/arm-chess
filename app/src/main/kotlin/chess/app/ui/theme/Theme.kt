/**
 * App theme (design §6.1). Follows the system dark setting. Dynamic colour is off in v1 (OQ-D2):
 * the fixed board palette and its contrast checks assume these schemes. Typography and shapes are
 * the Material 3 defaults with the system font.
 */
@Composable
fun ArmChessTheme(
    darkTheme: Boolean = isSystemInDarkTheme(),
    content: @Composable () -> Unit,
) {
    // The board palette is the same in both themes (design §6.2).
    CompositionLocalProvider(LocalBoardColors provides ArmChessBoardColors) {
        MaterialTheme(
            colorScheme = if (darkTheme) DarkColorScheme else LightColorScheme,
            content = content,
        )
    }
}

/** Theme values that Material 3 has no slot for. */
object ArmChessTheme {
    val boardColors: BoardColors
        @Composable
        @ReadOnlyComposable
        get() = LocalBoardColors.current
}
